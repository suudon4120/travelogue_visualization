import nltk
from nltk.translate.bleu_score import sentence_bleu, SmoothingFunction
import sys
from typing import List

def calculate_self_bleu(texts: List[str], tokenize_method: str = 'char') -> float:
    """
    生成されたテキストリストのSelf-BLEUスコアを計算します。
    
    Self-BLEU: あるテキストを「仮説」とし、残りのテキストを「参照」として
    BLEUスコアを計算し、その総平均をとる。
    スコアが低いほど、多様性が高い（互いに似ていない）ことを示す。

    Args:
        texts (List[str]): 評価対象の生成テキスト（文字列）のリスト。
        tokenize_method (str): トークナイズ方法。
                            'char' (文字単位) または 'mecab' (要MeCab)
                            
    Returns:
        float: Self-BLEU スコア (0.0 ~ 1.0)
    """
    
    if len(texts) < 2:
        print("警告: Self-BLEUの計算には2つ以上のテキストが必要です。", file=sys.stderr)
        return 0.0

    # --- トークナイズ処理 ---
    tokenized_texts = []
    
    if tokenize_method == 'char':
        print("トークナイズ方法: 文字単位 (character-based)")
        tokenized_texts = [list(text.replace(" ", "").replace("\n", "")) for text in texts]
        
    elif tokenize_method == 'mecab':
        print("トークナイズ方法: MeCab (形態素解析)")
        try:
            import MeCab
            # MeCabの辞書パスを環境に合わせて指定してください（例: '-d /usr/lib/x86_64-linux-gnu/mecab/dic/mecab-ipadic-neologd'）
            # パス指定が不要な場合は Tagger() のみ
            tagger = MeCab.Tagger("-Owakati")
            tokenized_texts = [tagger.parse(text).strip().split() for text in texts]
        except ImportError:
            print("エラー: 'mecab-python3' がインストールされていません。", file=sys.stderr)
            print("pip install mecab-python3 でインストールするか、tokenize_method='char' を使用してください。", file=sys.stderr)
            return -1.0
        except RuntimeError as e:
            print(f"エラー: MeCabの初期化に失敗しました。辞書パスが正しいか確認してください。 {e}", file=sys.stderr)
            return -1.0
    
    else:
        print(f"エラー: 未知のトークナイズ方法 '{tokenize_method}'", file=sys.stderr)
        return -1.0

    # -----------------------

    total_bleu_score = 0.0
    num_texts = len(tokenized_texts)
    
    # スムージング関数（ゼロ除算やn-gramがマッチしない場合に対応）
    # method1は加算スムージング(Add-1)で一般的
    chencherry = SmoothingFunction()

    # 各テキストを「仮説」としてループ
    for i in range(num_texts):
        # i番目のテキストを仮説(hypothesis)
        hypothesis = tokenized_texts[i]
        
        # i番目以外のテキストを参照(references)
        references = tokenized_texts[:i] + tokenized_texts[i+1:]
        
        # BLEUスコアを計算
        # weights=(0.25, 0.25, 0.25, 0.25) がデフォルト (BLEU-4)
        score = sentence_bleu(references, hypothesis, 
                            smoothing_function=chencherry.method1,
                            weights=(0.25, 0.25, 0.25, 0.25))
        
        total_bleu_score += score

    # 全テキストの平均スコアを返す
    return total_bleu_score / num_texts

